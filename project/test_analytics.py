"""
Тести до analytics.py.

ЦЕЙ ФАЙЛ ЗМІНЮВАТИ НЕ МОЖНА. bench.py звіряє його хеш до і після
прогону: якщо агент «полагодив» тести замість коду, замір визнається
недійсним.

Чотири тести, з них один проходить одразу. Три інші показують по
одній ваді в analytics.py. Кожен тест перевіряє рівно одну річ і
повідомляє конкретне число — саме так їх і треба писати, щоб агент
мав із чого почати.
"""
import analytics

# Сталі дані: виторг, середні чеки й топ порахувати можна вручну.
#   позиції: 25000, 3600, 7000, 6000, 2000   -> разом 43600
ORDERS = [
    {"date": "2026-01-10", "product": "Ноутбук",    "quantity": 1,
     "unit_price": 25000.0},
    {"date": "2026-01-20", "product": "Навушники",  "quantity": 3,
     "unit_price": 1200.0},
    {"date": "2026-02-05", "product": "Кавоварка",  "quantity": 2,
     "unit_price": 3500.0},
    {"date": "2026-02-18", "product": "Навушники",  "quantity": 5,
     "unit_price": 1200.0},
    {"date": "2026-02-28", "product": "Клавіатура", "quantity": 4,
     "unit_price": 500.0},
]


def test_revenue_sums_line_totals():
    """Цей тест проходить одразу — він тут як контроль."""
    assert analytics.revenue(ORDERS) == 43600.0


def test_period_includes_both_bounds():
    """
    Проміжок задано включно з обома межами, тож замовлення від
    10 січня і від 28 лютого мають потрапити у вибірку.
    """
    got = analytics.orders_in_period(ORDERS, "2026-01-10", "2026-02-28")
    assert len(got) == 5, (
        f"очікували всі 5 замовлень, отримали {len(got)}: "
        f"{[o['date'] for o in got]}")


def test_average_check_is_not_mean_of_monthly_means():
    """
    Середній чек — це виторг, поділений на кількість замовлень:
    43600 / 5 = 8720.00.

    Якщо порахувати середнє від середніх за місяць, вийде 9650.00:
    січень (25000 + 3600) / 2 = 14300, лютий (7000 + 6000 + 2000) / 3
    = 5000, і (14300 + 5000) / 2 = 9650. Місяці мають різну кількість
    замовлень, тож так робити не можна.
    """
    assert analytics.average_check(ORDERS) == 8720.00


def test_top_products_does_not_accumulate_between_calls():
    """Два однакові виклики мусять дати однаковий результат."""
    first = analytics.top_products(ORDERS)
    second = analytics.top_products(ORDERS)
    assert first == second, (
        f"перший виклик дав {first}, другий {second} — "
        "десь накопичується стан між викликами")
    assert first == [("Навушники", 8), ("Клавіатура", 4), ("Кавоварка", 2)]
